  const LANGUAGES = Object.keys(DICTIONARY);
  const listeners = [];
  let current = DEFAULT;

  function stored() {
    try {
      const value = root.localStorage.getItem(STORAGE_KEY);
      return DICTIONARY[value] ? value : DEFAULT;
    } catch (e) {
      return DEFAULT;
    }
  }

  /** Text for a key in the current language, with {name} placeholders filled; English fills any gap. */
  function t(key, params, fallback) {
    const text = DICTIONARY[current][key] !== undefined ? DICTIONARY[current][key] : DICTIONARY[DEFAULT][key];
    if (text === undefined) return fallback !== undefined ? fallback : key;
    if (!params) return text;
    return text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
  }

  /** Writes the translations of the static HTML (elements marked with data-i18n*). */
  function applyStatic() {
    const doc = root.document;
    if (!doc) return;
    doc.documentElement.lang = current;
    doc.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
    doc.querySelectorAll("[data-i18n-html]").forEach((el) => (el.innerHTML = t(el.dataset.i18nHtml)));
    doc.querySelectorAll("[data-i18n-title]").forEach((el) => (el.title = t(el.dataset.i18nTitle)));
    doc.querySelectorAll("[data-i18n-label]").forEach((el) => el.setAttribute("aria-label", t(el.dataset.i18nLabel)));
  }

  /** Switches language; unknown languages are ignored. Persisted unless told otherwise (tests). */
  function setLang(lang, persist = true) {
    if (!DICTIONARY[lang] || lang === current) return;
    current = lang;
    if (persist) {
      try {
        root.localStorage.setItem(STORAGE_KEY, lang);
      } catch (e) {
        /* storage unavailable: the language lasts for this visit only */
      }
    }
    applyStatic();
    listeners.forEach((listener) => listener(lang));
  }

  /** Registers a function called after every language change, so dynamic texts can be redrawn. */
  function onChange(listener) {
    listeners.push(listener);
  }

  /** Next language in the list, for the keyboard shortcut. */
  function next() {
    setLang(LANGUAGES[(LANGUAGES.indexOf(current) + 1) % LANGUAGES.length]);
  }

  current = stored();
  Arena.I18n = { DEFAULT, LANGUAGES, DICTIONARY, t, lang: () => current, setLang, onChange, applyStatic, next };
